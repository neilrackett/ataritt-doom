// Optional .W16 override for low-res (16-pen) weights/subset.
#define C2P_WEIGHTSET_MAGIC "W16"
#define C2P_WEIGHTSET_FILE_BYTES (4 + 16 + 256 * 16)
#define ATARI_W16_DEFAULT_FILE "stdoom.w16"

typedef struct
{
    char magic[4];
    unsigned char subset[16];
    unsigned char weights[256][16];
} C2P_WeightSet;

static C2P_WeightSet w16_data;
static int w16_loaded = 0;

static int install_w16_file(const char *path, int quiet)
{
    if (!path || !path[0])
        return 0;

    FILE *f = fopen(path, "rb");
    if (!f)
    {
        if (!quiet)
            printf("W16: could not open %s\n", path);
        return 0;
    }

    size_t n = fread(&w16_data, 1, sizeof(w16_data), f);
    fclose(f);
    if (n != sizeof(w16_data))
    {
        if (!quiet)
            printf("W16: expected %d bytes in %s (got %lu)\n", C2P_WEIGHTSET_FILE_BYTES, path, (unsigned long)n);
        return 0;
    }

    if (memcmp(w16_data.magic, C2P_WEIGHTSET_MAGIC, 4) != 0)
    {
        if (!quiet)
            printf("W16: bad magic in %s (expected W16\\0)\n", path);
        return 0;
    }

    w16_loaded = 1;
    printf("W16: installed custom weights from %s\n", path);
    return 1;
}

int atari_try_install_w16(const char *path)
{
    return install_w16_file(path, 0);
}

int atari_try_install_default_w16(void)
{
    return install_w16_file(ATARI_W16_DEFAULT_FILE, 1);
}

